#!/usr/bin/env python3
"""Generate src/unicode_table.rs from llama.cpp's src/unicode-data.cpp.

The pre-tokenizer of the vocabularies this crate supports asks four questions
of every code point: is it a letter, a number, a combining mark, or white
space. llama.cpp answers them from tables it generated from Python's
`unicodedata`; tokenizing exactly as llama.cpp does means using the very same
answers, not those of whatever Unicode version this machine's tools carry. So
the Rust table is produced from llama.cpp's own table and checked in.

Rerun with a llama.cpp tree, a fresh clone (nothing needs to be built):

    python3 -I crates/tokenizer/tools/gen_unicode.py <llama.cpp>

The tree is the argument, else the LLAMA_CPP_DIR environment variable; there is
no default. The output names the tree's revision; the table checked in came
from the llama.cpp fork (https://github.com/Piggidragon/llama.cpp) at
f8f346786. The output is `crates/tokenizer/src/unicode_table.rs`, relative to
this script, never the current directory. The script fails when llama.cpp's table does not look the
way it expects (it would otherwise write a table that is silently wrong).
"""

import os
import re
import subprocess
import sys

USAGE = "usage: gen_unicode.py <llama.cpp>, or LLAMA_CPP_DIR=<llama.cpp>"

# Flag bits of llama.cpp's `unicode_cpt_flags` for the categories.
NUMBER, LETTER, SEPARATOR, MARK, PUNCTUATION, SYMBOL, CONTROL, UNDEFINED = 0x2, 0x4, 0x8, 0x10, 0x20, 0x40, 0x80, 0x1
CATEGORIES = {NUMBER, LETTER, SEPARATOR, MARK, PUNCTUATION, SYMBOL, CONTROL, UNDEFINED}

# Our classes. `OTHER` covers everything that has some flag in llama.cpp (every
# code point does) and is none of the four.
OTHER, CLASS_LETTER, CLASS_NUMBER, CLASS_MARK, CLASS_SPACE = 0, 1, 2, 3, 4

MAX_CODEPOINTS = 0x110000


def block(text, name):
    start = text.index(name)
    return text[start : text.index("};", start)]


def llama_cpp_tree():
    """The llama.cpp tree of the argument, else of LLAMA_CPP_DIR."""
    if len(sys.argv) > 2:
        sys.exit(USAGE)
    tree = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("LLAMA_CPP_DIR", "")
    if not tree:
        sys.exit(USAGE)
    return os.path.abspath(tree)


def revision(tree):
    """The commit the tree is at, or "unknown" outside git."""
    try:
        return subprocess.run(
            ["git", "-C", tree, "rev-parse", "HEAD"], capture_output=True, text=True, check=True
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def main():
    tree = llama_cpp_tree()
    path = os.path.join(tree, "src", "unicode-data.cpp")
    text = open(path, encoding="utf8").read()

    ranges = [
        (int(a, 16), int(b, 16))
        for a, b in re.findall(r"\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}", block(text, "unicode_ranges_flags"))
    ]
    whitespace = {int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]+)", block(text, "unicode_set_whitespace"))}

    if ranges[0][0] != 0 or ranges[-1][0] != MAX_CODEPOINTS:
        sys.exit("the ranges do not span 0..0x110000")
    if any(a >= b for (a, _), (b, _) in zip(ranges, ranges[1:])):
        sys.exit("the range starts are not increasing")
    for start, flags in ranges[:-1]:
        if flags not in CATEGORIES:
            sys.exit(f"range at {start:#x} has flags {flags:#x}, which is not exactly one category")

    def class_of(flags):
        return {LETTER: CLASS_LETTER, NUMBER: CLASS_NUMBER, MARK: CLASS_MARK}.get(flags, OTHER)

    # Walk the ranges once, cutting them at the white space code points.
    merged = []

    def add(start, cls):
        if not merged or merged[-1][1] != cls:
            merged.append((start, cls))

    ws = sorted(whitespace)
    for (start, flags), (end, _) in zip(ranges, ranges[1:]):
        cls = class_of(flags)
        cut = start
        for cp in (w for w in ws if start <= w < end):
            if cp > cut:
                add(cut, cls)
            add(cp, CLASS_SPACE)
            cut = cp + 1
        if cut < end:
            add(cut, cls)
    # The codes of white space must not hide a letter, number or mark.
    for cp in ws:
        flags = [f for (s, f), (e, _) in zip(ranges, ranges[1:]) if s <= cp < e][0]
        if class_of(flags) != OTHER:
            sys.exit(f"white space {cp:#x} is also a letter, number or mark in llama.cpp's table")

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "unicode_table.rs")
    with open(out, "w", encoding="utf8") as f:
        f.write("//! Code point classes of llama.cpp's pre-tokenizer.\n")
        f.write("//!\n")
        f.write("//! GENERATED by `tools/gen_unicode.py` from llama.cpp's `src/unicode-data.cpp`\n")
        f.write(f"//! (revision {revision(tree)}). Do not edit by hand; rerun the script.\n")
        f.write("//!\n")
        f.write("//! `RANGES[i] = (start, class)` says that the code points from `start` to the next\n")
        f.write("//! start (exclusive) have class `class`. The last entry starts at 0x110000.\n\n")
        f.write("pub(crate) const OTHER: u8 = 0;\n")
        f.write("pub(crate) const LETTER: u8 = 1;\n")
        f.write("pub(crate) const NUMBER: u8 = 2;\n")
        f.write("pub(crate) const MARK: u8 = 3;\n")
        f.write("pub(crate) const SPACE: u8 = 4;\n\n")
        f.write(f"pub(crate) static RANGES: [(u32, u8); {len(merged) + 1}] = [\n")
        per_line = 6
        entries = [f"({s:#08x}, {c})" for s, c in merged] + [f"({MAX_CODEPOINTS:#08x}, {OTHER})"]
        for i in range(0, len(entries), per_line):
            f.write("    " + ", ".join(entries[i : i + per_line]) + ",\n")
        f.write("];\n")
    print(f"wrote {out}: {len(merged) + 1} ranges from {len(ranges)} in llama.cpp, {len(ws)} white space code points")


if __name__ == "__main__":
    main()
