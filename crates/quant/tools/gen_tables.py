#!/usr/bin/env python3
"""Generate src/tables.rs from ggml's ggml-common.h.

The codebook formats (IQ1, IQ2, IQ3, IQ4_NL) and the FP4 formats decode through
lookup tables that ggml keeps in `ggml/src/ggml-common.h`. Retyping 4000 hex
constants would be an invitation for a typo that no review catches, so the Rust
tables are produced from the header by this script and checked in.

Rerun with a llama.cpp tree, a fresh clone (nothing needs to be built):

    python3 -I crates/quant/tools/gen_tables.py <llama.cpp>

The tree is the argument, else the LLAMA_CPP_DIR environment variable; there is
no default. The output names the tree's revision; the tables checked in came
from the llama.cpp fork (https://github.com/Piggidragon/llama.cpp) at
f8f346786. The output is `crates/quant/src/tables.rs`, relative to this script,
never the current directory. The script fails (instead of writing a short table) when a table
does not have the number of entries its declaration promises.
"""

import os
import re
import subprocess
import sys

USAGE = "usage: gen_tables.py <llama.cpp>, or LLAMA_CPP_DIR=<llama.cpp>"

# (name in the header, name in Rust, doc comment). Order is the order in the output.
WANTED = [
    ("kmask_iq2xs", "KMASK_IQ2XS", "Bit `j` of a sign byte, for the sign of value `j` in a group of 8."),
    (
        "ksigns_iq2xs",
        "KSIGNS_IQ2XS",
        "Sign byte of a 7-bit sign index: the 7 index bits plus one parity bit, so a\n"
        "/// group of 8 always has an even number of negative values.",
    ),
    ("kvalues_iq4nl", "KVALUES_IQ4NL", "The 16 non-linear levels of IQ4_NL and IQ4_XS."),
    (
        "kvalues_fp4",
        "KVALUES_MXFP4",
        "The 16 E2M1 levels of MXFP4 and NVFP4, doubled so they are integers. ggml\n"
        "/// names this table `kvalues_fp4` and aliases it to `kvalues_mxfp4`.",
    ),
    ("iq2xxs_grid", "IQ2XXS_GRID", "IQ2_XXS codebook: 256 groups of 8 magnitudes, one per byte (little endian)."),
    ("iq2xs_grid", "IQ2XS_GRID", "IQ2_XS codebook: 512 groups of 8 magnitudes, one per byte (little endian)."),
    ("iq2s_grid", "IQ2S_GRID", "IQ2_S codebook: 1024 groups of 8 magnitudes, one per byte (little endian)."),
    ("iq3xxs_grid", "IQ3XXS_GRID", "IQ3_XXS codebook: 256 groups of 4 magnitudes, one per byte (little endian)."),
    ("iq3s_grid", "IQ3S_GRID", "IQ3_S codebook: 512 groups of 4 magnitudes, one per byte (little endian)."),
    (
        "iq1s_grid",
        "IQ1S_GRID",
        "IQ1_S and IQ1_M codebook: 2048 groups of 8 values in {-1, 0, 1}, one signed\n"
        "/// byte each (little endian).",
    ),
]

RUST_TYPES = {"uint8_t": "u8", "int8_t": "i8", "uint32_t": "u32", "uint64_t": "u64"}
PER_LINE = {"u8": 16, "i8": 16, "u32": 8, "u64": 4}
WIDTH = {"u8": 4, "i8": 4, "u32": 10, "u64": 18}


def parse_tables(text):
    defines = dict(re.findall(r"^#define\s+(\w+)\s+(\d+)\s*$", text, re.M))
    tables = {}
    pattern = re.compile(r"GGML_TABLE_BEGIN\(\s*(\w+)\s*,\s*(\w+)\s*,\s*(\w+)\s*\)(.*?)GGML_TABLE_END\(\)", re.S)
    for ctype, name, size, body in pattern.findall(text):
        if not size.isdigit() and size not in defines:
            continue  # the `#define GGML_TABLE_BEGIN(type, name, size)` lines themselves
        size = int(defines.get(size, size))
        body = re.sub(r"//[^\n]*", "", body)
        body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
        values = [int(v, 0) for v in re.findall(r"-?0[xX][0-9a-fA-F]+|-?\d+", body)]
        if len(values) != size:
            sys.exit(f"{name}: declared {size} entries, found {len(values)}")
        # A name can occur under several #if branches (one per backend); they must agree.
        if name in tables and tables[name] != (ctype, values):
            sys.exit(f"{name}: two different definitions in the header")
        tables[name] = (ctype, values)
    return tables


def format_value(value, rust_type):
    if rust_type.startswith("i"):
        return f"{value}".rjust(WIDTH[rust_type])
    return f"0x{value:0{WIDTH[rust_type] - 2}x}"


def llama_cpp_tree():
    """The llama.cpp tree of the argument, else of LLAMA_CPP_DIR."""
    if len(sys.argv) > 2:
        sys.exit(USAGE)
    tree = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("LLAMA_CPP_DIR", "")
    if not tree:
        sys.exit(USAGE)
    return os.path.abspath(tree)


def main():
    tree = llama_cpp_tree()
    header = os.path.join(tree, "ggml", "src", "ggml-common.h")
    here = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.join(here, "..", "src", "tables.rs")
    with open(header, encoding="utf-8") as f:
        tables = parse_tables(f.read())

    try:
        rev = subprocess.run(
            ["git", "-C", tree, "rev-parse", "HEAD"],
            capture_output=True, text=True, check=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        rev = "unknown"

    lines = [
        "//! Lookup tables of the codebook and FP4 formats.",
        "//!",
        "//! GENERATED by `tools/gen_tables.py` from ggml's `ggml-common.h` (llama.cpp",
        f"//! revision {rev}). Do not edit by hand; rerun the script.",
        "//!",
        "//! The tables keep ggml's element types. The grids are arrays of `u64` or `u32` that",
        "//! ggml reads back as bytes through a pointer cast, which on the little-endian",
        "//! machines ggml targets means byte `j` of an entry is `(entry >> (8 * j)) & 0xff`.",
        "//! The decoders here do the same with `to_le_bytes`, so they give the same bytes on",
        "//! any host.",
        "",
    ]
    for c_name, rust_name, doc in WANTED:
        if c_name not in tables:
            sys.exit(f"{c_name} not found in {header}")
        ctype, values = tables[c_name]
        rust_type = RUST_TYPES[ctype]
        lines.append(f"/// {doc}")
        lines.append(f"pub(crate) static {rust_name}: [{rust_type}; {len(values)}] = [")
        step = PER_LINE[rust_type]
        for i in range(0, len(values), step):
            row = ", ".join(format_value(v, rust_type) for v in values[i : i + step])
            lines.append(f"    {row},")
        lines.append("];")
        lines.append("")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {os.path.normpath(out_path)} ({len(WANTED)} tables, llama.cpp {rev})")


if __name__ == "__main__":
    main()
