#!/usr/bin/env python3
"""Writes iq_tables.cuh: the codebooks of the i-quants for the GPU kernels.

The tables are the ones the CPU reference decoder uses (crates/quant/src/tables.rs,
generated there from ggml-common.h), so the kernels and the reference cannot
disagree about them. Run from this directory after tables.rs changes:

    python3 gen_iq_tables.py > iq_tables.cuh
"""
import re
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent.parent / "quant" / "src" / "tables.rs"
text = SRC.read_text()


def table(name, ctype):
    m = re.search(r"static %s: \[(\w+); (\d+)\] = \[(.*?)\n\];" % name, text, re.S)
    assert m, name
    values = [int(v, 16) if v.startswith(("0x", "-0x")) else int(v) for v in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", m.group(3))]
    assert len(values) == int(m.group(2)), (name, len(values))
    return values


def emit(name, ctype, values, per_line, width):
    out = ["static __device__ __align__(16) const %s %s[%d] = {" % (ctype, name, len(values))]
    for i in range(0, len(values), per_line):
        chunk = values[i : i + per_line]
        out.append("    " + ", ".join(("0x%0" + str(width) + "x") % v if v >= 0 else str(v) for v in chunk) + ",")
    out.append("};")
    return "\n".join(out)


print("// GENERATED by gen_iq_tables.py from crates/quant/src/tables.rs. Do not edit by hand.")
print("//")
print("// Codebooks of the i-quant types, as the CPU decoder has them: a grid entry is 8 (u64)")
print("// or 4 (u32) magnitudes, one per byte, least significant byte first.")
print("#pragma once")
print()
print('#include "common.cuh"')
print()
print(emit("ares_ksigns_iq2xs", "uint8_t", table("KSIGNS_IQ2XS", "u8"), 16, 2))
print()
print(emit("ares_kvalues_iq4nl", "int8_t", table("KVALUES_IQ4NL", "i8"), 16, 2))
print()
print(emit("ares_iq2xs_grid", "uint64_t", table("IQ2XS_GRID", "u64"), 4, 16))
print()
print(emit("ares_iq2s_grid", "uint64_t", table("IQ2S_GRID", "u64"), 4, 16))
print()
print(emit("ares_iq3xxs_grid", "uint32_t", table("IQ3XXS_GRID", "u32"), 8, 8))
print()
print(emit("ares_iq3s_grid", "uint32_t", table("IQ3S_GRID", "u32"), 8, 8))
