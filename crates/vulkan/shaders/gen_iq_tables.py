#!/usr/bin/env python3
"""Writes iq_tables.glsl: the codebooks of the i-quants for the Vulkan kernels.

The tables are the ones the CPU reference decoder uses (crates/quant/src/tables.rs),
so the kernels and the reference cannot disagree about them; the CUDA kernels get
theirs the same way (crates/cuda/kernels/gen_iq_tables.py). Run from this directory
after tables.rs changes:

    python3 gen_iq_tables.py > iq_tables.glsl

A unit test of the crate (`iq_tables_match_the_cpu_decoder`) compares the file with
the tables of ares-quant, so a stale copy fails the build's tests.
"""
import re
from pathlib import Path

SRC = Path(__file__).resolve().parent.parent.parent / "quant" / "src" / "tables.rs"
text = SRC.read_text()


def table(name):
    m = re.search(r"static %s: \[(\w+); (\d+)\] = \[(.*?)\n\];" % name, text, re.S)
    assert m, name
    values = [
        int(v, 16) if "0x" in v else int(v)
        for v in re.findall(r"-?0x[0-9a-fA-F]+|-?\d+", m.group(3))
    ]
    assert len(values) == int(m.group(2)), (name, len(values))
    return values


def emit_u32(name, values):
    out = ["const uint %s[%d] = uint[](" % (name, len(values))]
    for i in range(0, len(values), 8):
        chunk = values[i : i + 8]
        out.append("    " + ", ".join("0x%08xu" % v for v in chunk) + ("," if i + 8 < len(values) else ""))
    out.append(");")
    return "\n".join(out)


def emit_u64(name, values):
    out = ["const uvec2 %s[%d] = uvec2[](" % (name, len(values))]
    for i in range(0, len(values), 4):
        chunk = values[i : i + 4]
        out.append(
            "    "
            + ", ".join("uvec2(0x%08xu, 0x%08xu)" % (v & 0xFFFFFFFF, v >> 32) for v in chunk)
            + ("," if i + 4 < len(values) else "")
        )
    out.append(");")
    return "\n".join(out)


def emit_i32(name, values):
    return "const int %s[%d] = int[](%s);" % (name, len(values), ", ".join(str(v) for v in values))


# The big codebooks go to a binary file that the host uploads to the device once; the
# kernels copy what they need to shared memory from there. (As constant arrays in the
# shaders they were indexed per lane when copied, which the hardware serialises.)
blobs = [
    ("IQ2XXS", "IQ2XXS_GRID", 8),
    ("IQ2XS", "IQ2XS_GRID", 8),
    ("IQ2S", "IQ2S_GRID", 8),
    ("IQ1S", "IQ1S_GRID", 2),
    ("IQ3XXS", "IQ3XXS_GRID", 4),
    ("IQ3S", "IQ3S_GRID", 4),
]
data = bytearray()
offsets = []


def pack_iq1(values):
    """IQ1_S / IQ1_M grid entries (8 bytes in {-1, 0, 1}) as 16 bits: 2 bits per value,
    value + 1, the first value in the low bits."""
    out = []
    for v in values:
        bits = 0
        for j in range(8):
            byte = (v >> (8 * j)) & 0xFF
            signed = byte - 256 if byte >= 128 else byte
            assert signed in (-1, 0, 1)
            bits |= (signed + 1) << (2 * j)
        out.append(bits)
    return out

for name, table_name, width in blobs:
    values = table(table_name)
    if name == "IQ1S":
        values = pack_iq1(values)
    offsets.append((name, len(data), len(values)))
    for v in values:
        data += v.to_bytes(width, "little")
    while len(data) % 16:
        data.append(0)
(Path(__file__).resolve().parent / "iq_tables.bin").write_bytes(bytes(data))

print("// GENERATED by gen_iq_tables.py from crates/quant/src/tables.rs. Do not edit by hand.")
print("//")
print("// The small codebook, and where the large ones are in iq_tables.bin, which the host")
print("// uploads to the device (`Quantized::load`) and hands to the kernels as `tables`. An")
print("// entry is 8 magnitudes (8 bytes: bytes 0..3 are the first uint, 4..7 the second) or 4")
print("// (4 bytes), one per byte, least significant byte first, as in the CPU decoder.")
print()
print(emit_i32("ares_kvalues_iq4nl", table("KVALUES_IQ4NL")))
print()
print(emit_i32("ares_kvalues_mxfp4", table("KVALUES_MXFP4")))
print()
for name, offset, count in offsets:
    print("const uint TBL_%s = %d;  // %d entries" % (name, offset, count))
